// Build a Question from an ordered list (least niche -> most niche).
// The first answers are Common, the very last one is the One in a Luffillion.
export function ranked(id: string, prompt: string, hint: string, list: string, matchAs?: string): Question {
  const seen = new Set<string>();
  const items = list
    // "Ryu Ryu no Mi, Model: Pteranodon" is one answer: never split before "Model:".
    .split(/,(?!\s*Model:)/)
    .map((s) => s.trim())
    .filter(Boolean)
    .map((k) => D[k] ?? k)
    .filter((full) => {
      const key = full.split("|")[0].toLowerCase();
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    });
  const n = items.length;
  const luff = items.slice(-1);
  const rest = items.slice(0, -1);
  const nc = Math.min(10, Math.max(2, Math.round(n * 0.08)));
  const common = rest.slice(0, nc);
  const remaining = rest.slice(nc);
  // Tuned so answers beyond the top ~20% reach Rare, and deep lore reaches Epic:
  const u = Math.max(1, Math.round(remaining.length * 0.14));
  const r = Math.max(1, Math.round(remaining.length * 0.36));
  return {
    id,
    prompt,
    hint,
    matchAs,
    tiers: {
      common,
      uncommon: remaining.slice(0, u),
      rare: remaining.slice(u, u + r),
      epic: remaining.slice(u + r),
      luffillion: luff,
    },
  };
}

